package br.com.hestia.rag.service;

import br.com.hestia.aprendizagem.AcessoCapacitacao;
import br.com.hestia.empresa.model.Empresa;
import br.com.hestia.rag.service.InteracaoRagService.Modo;
import br.com.hestia.rag.service.InteracaoRagService.Pergunta;
import br.com.hestia.registro.service.RegistroUsoIAService;
import br.com.hestia.reutilizavel.model.RespostaReutilizavel;
import br.com.hestia.reutilizavel.repository.RespostaReutilizavelRepository;
import br.com.hestia.reutilizavel.service.AcessoRespostaService;
import br.com.hestia.reutilizavel.service.RespostaReutilizavelService;
import br.com.hestia.shared.RepositorioIntegracao;
import br.com.hestia.usuario.model.PerfilUsuario;
import br.com.hestia.usuario.model.Usuario;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.test.util.ReflectionTestUtils;

import java.util.List;
import java.util.Set;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;

class FluxoRagPoliticaEmpresaIntegrationTest {

    private static final String PERGUNTA = "Posso enviar dados pessoais para uma ferramenta de IA?";
    private static final String POLITICA = """
            Política de uso responsável de IA da empresa:
            dados pessoais ou confidenciais não podem ser enviados a ferramentas não aprovadas.
            Em caso de dúvida, o colaborador deve procurar o gestor responsável.
            """;

    private JdbcTemplate jdbc;
    private BuscaVetorialService busca;
    private GeracaoRagService geracao;
    private RespostaReutilizavelService respostas;
    private InteracaoRagService service;
    private Usuario usuario;

    @BeforeEach
    void preparar() {
        var dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:rag_" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1",
                "sa",
                ""
        );
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("""
                CREATE TABLE interacoes_rag (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    empresa_id BIGINT NOT NULL,
                    usuario_id BIGINT NOT NULL,
                    chave VARCHAR(100) NOT NULL,
                    pergunta TEXT NOT NULL,
                    modo VARCHAR(30) NOT NULL,
                    estado VARCHAR(60) NOT NULL,
                    resposta TEXT,
                    fontes TEXT NOT NULL,
                    modelo VARCHAR(150),
                    tokens_entrada BIGINT,
                    tokens_saida BIGINT,
                    registro_uso_id BIGINT,
                    criada_em TIMESTAMP NOT NULL,
                    UNIQUE (empresa_id, usuario_id, chave)
                )
                """);
        jdbc.execute("""
                CREATE TABLE resposta_versoes (
                    resposta_id BIGINT NOT NULL,
                    numero_versao INTEGER NOT NULL,
                    conteudo_sha256 VARCHAR(64) NOT NULL
                )
                """);

        var fonte = fontePolitica();
        jdbc.update(
                "INSERT INTO resposta_versoes(resposta_id, numero_versao, conteudo_sha256) VALUES (?, ?, ?)",
                fonte.getId(),
                1,
                AcessoCapacitacao.hash(fonte.getPromptOriginal() + "\n" + fonte.getRespostaGerada())
        );

        usuario = new Usuario();
        usuario.setId(10L);
        usuario.setAtivo(true);
        usuario.setPerfil(PerfilUsuario.FUNCIONARIO);
        usuario.setEmpresa(new Empresa(1L, "QSoft", "00000000000000", null, null));

        var repository = mock(RespostaReutilizavelRepository.class);
        when(repository.recuperarAutorizadas(
                eq(1L), eq(PerfilUsuario.FUNCIONARIO), eq(77L), isNull(),
                eq(false), any(), any()
        )).thenReturn(List.of(fonte));

        var acessoResposta = new AcessoRespostaService(repository);
        busca = mock(BuscaVetorialService.class);
        when(busca.buscarSemelhantes(1L, PERGUNTA, 5)).thenReturn(List.of(fonte));

        geracao = mock(GeracaoRagService.class);
        when(geracao.gerar(eq(PERGUNTA), anyList())).thenReturn(
                new GeracaoRagService.Gerada(
                        "Não envie dados pessoais a ferramentas não aprovadas.",
                        "modelo-validacao",
                        120L,
                        24L
                )
        );

        var acessoCapacitacao = mock(AcessoCapacitacao.class);
        var db = new RepositorioIntegracao(jdbc, acessoCapacitacao);
        service = new InteracaoRagService(
                db,
                busca,
                acessoResposta,
                geracao,
                respostas = mock(RespostaReutilizavelService.class),
                mock(RegistroUsoIAService.class),
                0L
        );
    }

    @Test
    void consultaRecuperaPoliticaAutorizadaEPreservaFonteNoHistorico() {
        var resultado = service.perguntar(
                usuario,
                new Pergunta("consulta-politica-1", PERGUNTA, Modo.CONSULTAR, null)
        );

        assertThat(resultado.estado()).isEqualTo("REUTILIZADA");
        assertThat(resultado.resposta()).isEqualTo(POLITICA);
        assertThat(resultado.fontes()).singleElement().satisfies(fonte -> {
            assertThat(fonte.id()).isEqualTo(77L);
            assertThat(fonte.titulo()).isEqualTo("Política corporativa de proteção de dados no uso de IA");
            assertThat(fonte.versao()).isEqualTo(1);
            assertThat(fonte.conteudoSha256()).hasSize(64);
        });

        var repetida = service.perguntar(
                usuario,
                new Pergunta("consulta-politica-1", PERGUNTA, Modo.CONSULTAR, null)
        );
        assertThat(repetida.id()).isEqualTo(resultado.id());
        verify(busca, times(1)).buscarSemelhantes(1L, PERGUNTA, 5);

        assertThat(service.historico(usuario))
                .extracting(InteracaoRagService.Resultado::id)
                .containsExactly(resultado.id());
        verify(respostas).registrarReutilizacao(77L, 10L);
    }

    @Test
    void geraRespostaSomenteComOTrechoDaPoliticaAutorizada() {
        var resultado = service.perguntar(
                usuario,
                new Pergunta("gerar-politica-1", PERGUNTA, Modo.GERAR_NOVA, null)
        );

        assertThat(resultado.estado()).isEqualTo("GERADA_COM_FONTES");
        assertThat(resultado.resposta())
                .isEqualTo("Não envie dados pessoais a ferramentas não aprovadas.");
        assertThat(resultado.fontes()).singleElement()
                .extracting(InteracaoRagService.Fonte::trecho)
                .isEqualTo(POLITICA);

        verify(geracao).gerar(
                eq(PERGUNTA),
                argThat(trechos -> trechos.size() == 1
                        && trechos.getFirst().contains("[Fonte 77]")
                        && trechos.getFirst().contains("dados pessoais"))
        );
    }

    @Test
    void informaAusenciaSemInventarRespostaQuandoNaoHaPoliticaAutorizada() {
        when(busca.buscarSemelhantes(1L, "Qual é a política de viagens?", 5))
                .thenReturn(List.of());

        var resultado = service.perguntar(
                usuario,
                new Pergunta(
                        "sem-politica-1",
                        "Qual é a política de viagens?",
                        Modo.GERAR_NOVA,
                        null
                )
        );

        assertThat(resultado.estado()).isEqualTo("SEM_CONTEUDO_AUTORIZADO");
        assertThat(resultado.resposta()).isNull();
        assertThat(resultado.fontes()).isEmpty();
        verifyNoInteractions(geracao);
    }

    @Test
    void falhaDaGeracaoNaoViraRespostaInventadaNemHistoricoDeSucesso() {
        when(geracao.gerar(eq(PERGUNTA), anyList()))
                .thenThrow(new org.springframework.web.server.ResponseStatusException(
                        org.springframework.http.HttpStatus.SERVICE_UNAVAILABLE,
                        "Modelo indisponível"
                ));

        assertThatThrownBy(() -> service.perguntar(
                usuario,
                new Pergunta("geracao-indisponivel-1", PERGUNTA, Modo.GERAR_NOVA, null)
        )).isInstanceOf(org.springframework.web.server.ResponseStatusException.class);

        assertThat(jdbc.queryForObject(
                "SELECT count(*) FROM interacoes_rag WHERE chave=?",
                Long.class,
                "geracao-indisponivel-1"
        )).isZero();
    }

    private RespostaReutilizavel fontePolitica() {
        var fonte = new RespostaReutilizavel();
        ReflectionTestUtils.setField(fonte, "id", 77L);
        fonte.setUsuarioId(10L);
        fonte.setEmpresaId(1L);
        fonte.setPromptOriginal("Política corporativa de proteção de dados no uso de IA");
        fonte.setRespostaGerada(POLITICA);
        fonte.setPossuiDadosSensiveis(false);
        fonte.setReutilizavel(true);
        fonte.setPerfisPermitidos(Set.of(PerfilUsuario.FUNCIONARIO));
        return fonte;
    }
}
