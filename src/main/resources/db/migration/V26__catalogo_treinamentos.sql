CREATE TABLE catalogo_treinamentos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
 empresa_id BIGINT NOT NULL REFERENCES empresas(id),
 anterior_id BIGINT REFERENCES catalogo_treinamentos(id),
 titulo VARCHAR(250) NOT NULL,
 descricao VARCHAR(2000) NOT NULL,
 conteudo TEXT NOT NULL,
 tema VARCHAR(80) NOT NULL,
 duracao_minutos INT NOT NULL,
 fonte VARCHAR(2000) NOT NULL,
 autorizacao_uso VARCHAR(2000) NOT NULL,
 objetivo VARCHAR(2000) NOT NULL,
 publico VARCHAR(2000) NOT NULL,
 atividade TEXT NOT NULL,
 criterio_aceite TEXT NOT NULL,
 questionario TEXT NOT NULL,
 conteudo_sha256 VARCHAR(64) NOT NULL,
 estado VARCHAR(30) NOT NULL DEFAULT 'RASCUNHO',
 criado_por BIGINT NOT NULL REFERENCES usuarios(id),
 criado_em TIMESTAMP NOT NULL,
 revisado_por BIGINT REFERENCES usuarios(id),
 revisado_em TIMESTAMP,
 evidencia_revisao VARCHAR(2000),
 publicado_em TIMESTAMP,
 retirado_em TIMESTAMP,
 motivo_retirada VARCHAR(2000)
);
